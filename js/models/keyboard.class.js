/**
 * Class representing the keyboard input state.
 */
class Keyboard {

    /** Default state of the left key (not pressed) */
    LEFT = false;

    /** Default state of the right key (not pressed) */
    RIGHT = false;

    /** Default state of the up key (not pressed) */
    UP = false;

    /** Default state of the down key (not pressed) */
    DOWN = false;

    /** Default state of the space key (not pressed) */
    SPACE = false;
}
